            <h2 class="csp-h2">Preguntas frecuentes</h2>
            <div style="margin-top:24px">
                <details open>
                    <summary>¿Qué pasa si tengo más de 2,500 pólizas?</summary>
                    <p>El excedente cuesta $10 al mes por cada 500 pólizas adicionales, con un tope de $150 al mes: una cartera de 20,000 pólizas paga lo mismo que una de 10,000.</p>
                </details>
                <details>
                    <summary>¿Qué cuenta como póliza activa?</summary>
                    <p>Las pólizas vigentes en tu cartera durante ese mes. Las canceladas o vencidas dejan de contar automáticamente, y las cotizaciones que aún no se emiten no cuentan. La medición es mensual, así que si tu cartera baja, tu factura baja.</p>
                </details>
                <details>
                    <summary>¿Qué pasa si necesito más de lo incluido?</summary>
                    <p>Te avisamos antes de que llegues al límite y puedes ampliar la capacidad con un paquete adicional, a las tarifas publicadas más arriba. No hay subida automática de plan.</p>
                </details>
                <details>
                    <summary>¿Puedo contratar Independiente y sumar módulos después?</summary>
                    <p>Sí. Independiente es un plan completo por sí mismo, y puedes activar Otto IA o Inbox cuando los necesites. Si terminas usando ambos, el plan Profesional te sale más barato que los tres por separado (<span data-an="$139" data-me="$174">$139</span> contra <span data-an="$158" data-me="$188">$158</span> al mes).</p>
                </details>
                <details>
                    <summary>¿Cómo se cobra WhatsApp exactamente?</summary>
                    <p>Hay dos cobros independientes:</p>
                    <ol>
                        <li><b>Mensajes (a Meta):</b> los pagas directamente a Meta, según sus tarifas por país y tipo de mensaje.</li>
                        <li><b>Uso de la plataforma (a Escala):</b> según tu plan y la capacidad que contrates.</li>
                    </ol>
                </details>
                <details>
                    <summary>¿Cómo se cuenta una automatización?</summary>
                    <p>Contamos <b>acciones ejecutadas</b>, no flujos creados. Una acción es cada paso que corre dentro de un flujo: enviar un email, actualizar un campo, crear una tarea, esperar, ramificar. Puedes construir todos los flujos que quieras — un flujo de 5 pasos que se dispara 100 veces consume 500 acciones, y uno de un solo paso que corre 100 veces consume 100.</p>
                </details>
                <details>
                    <summary>¿Qué pasa si llego al límite de acciones?</summary>
                    <p>Te avisamos antes de que llegues al límite. Si tu operación necesita más, lo ajustamos contigo — las acciones de automatización no tienen tarifa de excedente.</p>
                </details>
                <details>
                    <summary>¿Los precios incluyen impuestos?</summary>
                    <p>No. Todos los precios están en dólares estadounidenses y no incluyen los impuestos locales de tu país, que se agregan en la factura según corresponda.</p>
                </details>
                <details>
                    <summary>Si soy cliente y suben los precios, ¿me afecta?</summary>
                    <p>Mantienes tu tarifa hasta la siguiente renovación, y te avisamos con anticipación antes de cualquier cambio. Nunca modificamos el precio de un contrato vigente.</p>
                </details>
                <details>
                    <summary>¿Hay permanencia mínima?</summary>
                    <p>No. Puedes pagar mes a mes y cancelar cuando quieras. El plan anual existe solo para darte el 20% de descuento.</p>
